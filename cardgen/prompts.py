def build_user_prompt(product: ProductInput, missing_fields: list[str]) -> str:
    payload = {
        "name": product.name,
        "manufacturer": product.manufacturer or None,
        "specs": product.filled_specs,
        "description": product.description or None,
    }
    # Символ < экранируется, чтобы текст товара не мог закрыть блок данных.
    data = json.dumps(payload, ensure_ascii=False, indent=2).replace("<", "\\u003c")
    missing = ", ".join(missing_fields) if missing_fields else "нет"
    return (
        f"<product_data>\n{data}\n</product_data>\n\n"
        f"Поля без данных (их значения не указывай): {missing}.\n"
        "Подготовь черновик карточки."
    )


def build_repair_prompt(issues: list[Issue]) -> str:
    listed = "\n".join(f"- {issue.field}: {issue.message}" for issue in issues)
    return (
        "Автоматическая проверка нашла замечания:\n"
        f"{listed}\n\n"
        "Верни карточку целиком, исправив только эти замечания. Если значения нет в "
        "<product_data>, удали его, а не заменяй другим. Остальные требования остаются в силе."
    )
